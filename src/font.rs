//! Built-in 5x7 bitmap font. ASCII 0x20..=0x7E only; unsupported codepoints
//! are drawn as a blank advance so text width stays deterministic.
//!
//! Each glyph is 7 rows of 5 pixels. `glyph()` returns per-row bitmasks where
//! bit `4 - column` is set for a lit pixel; all arithmetic is integer.

/// Width of one glyph in font pixels.
pub const GLYPH_W: i64 = 5;
/// Height of one glyph in font pixels.
pub const GLYPH_H: i64 = 7;
/// Horizontal advance per glyph, including one blank column, for a given scale.
pub fn advance(scale: i64) -> i64 {
    (GLYPH_W + 1) * scale
}

