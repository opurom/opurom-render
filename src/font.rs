/// Coverage rows for one codepoint in the high-resolution set, or `None`
/// when the character is not part of it. Row `r`, column `c` is
/// `(rows[r] >> ((SMOOTH_W - 1 - c) * 4)) & 0xF`, a value in `0..=SMOOTH_LEVEL`.
pub fn smooth_glyph(ch: char) -> Option<[u64; SMOOTH_H as usize]> {
    SMOOTH_GLYPHS
        .iter()
        .find(|(c, _)| *c == ch)
        .map(|(_, rows)| *rows)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_printable_ascii() {
        for code in 0x20u8..=0x7e {
            assert!(glyph(code as char).is_some(), "missing glyph {code}");
        }
        assert!(glyph('\u{4e2d}').is_none());
    }

    #[test]
    fn glyph_bits_are_stable() {
        assert_eq!(glyph('A').unwrap()[3], 0b11111);
        assert_eq!(glyph(' ').unwrap(), [0; 7]);
    }

    #[test]
    fn descender_glyphs_are_distinct_from_digits() {
        let g = glyph('g').unwrap();
        let q = glyph('q').unwrap();
        let nine = glyph('9').unwrap();
        assert_ne!(g, nine, "g must not read as 9");
        assert_ne!(q, nine, "q must not read as 9");
        assert_ne!(g, q, "g and q need different descenders");
        // g ends in a left hook, q in a straight stem, 9 in a right-leaning tail.
        assert_ne!(g[5], q[5]);
        assert_ne!(g[6], nine[6]);
        assert_eq!(g[6], 0b11110);
    }

    #[test]
    fn p_and_y_have_descenders_distinct_from_capitals() {
        let (p, capital_p) = (glyph('p').unwrap(), glyph('P').unwrap());
        let (y, capital_y) = (glyph('y').unwrap(), glyph('Y').unwrap());
        assert_ne!(p, capital_p, "p must not read as P");
        assert_ne!(y, capital_y, "y must not read as Y");
        // Both bowls start at x-height; their tails reach the bottom row with
        // ink beyond the capitals' straight stems.
        assert_eq!(p[0] | p[1], 0);
        assert_eq!(y[0] | y[1], 0);
        assert_ne!(
            p[6] & !capital_p[6],
            0,
            "p needs descender ink past P's stem"
        );
        assert_ne!(
            y[6] & !capital_y[6],
            0,
            "y needs descender ink past Y's stem"
        );
    }

    #[test]
    fn smooth_font_covers_common_ui_ascii() {
        // Every printable ASCII letter and digit must have a high-resolution
        // glyph so ordinary labels never fall back to the block bitmap.
        let cell = |row: u64, c: i64| -> u64 { (row >> ((SMOOTH_W - 1 - c) * 4)) & 0xF };
        for code in 0x20u8..=0x7e {
            let ch = code as char;
            if ch.is_ascii_alphanumeric() || ch.is_ascii_whitespace() {
                let rows = smooth_glyph(ch).unwrap_or_else(|| panic!("no smooth glyph {ch:?}"));
                if ch != ' ' {
                    assert!(
                        rows.iter().any(|&r| r != 0),
                        "smooth glyph {ch:?} must not be blank"
                    );
                    assert!(
                        rows.iter()
                            .all(|&r| (0..SMOOTH_W).all(|c| cell(r, c) <= SMOOTH_LEVEL as u64)),
                        "smooth glyph {ch:?} coverage exceeds level"
                    );
                }
            }
        }
        assert!(smooth_glyph('\u{4e2d}').is_none());
    }
}
